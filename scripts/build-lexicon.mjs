// 用已下载的原始数据生成随网站发布的词表，平时开发无需再次运行。
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
const base = process.argv[2]
const dictionary = new Map()
for (const line of readFileSync(join(base, 'fuzzy-cmudict.txt'), 'utf8').split('\n')) {
  const [term, ...phones] = line.trim().split(/\s+/)
  if (!/^[a-z][a-z'-]*$/.test(term)) continue
  dictionary.set(term, phones.join(' ').split(' #')[0])
}
const words = readFileSync(join(base, 'fuzzy-frequency.txt'), 'utf8').trim().split(/\s+/)
const extras = ['breathe', 'breath', 'breathing', 'breadth', 'wreath', 'throughout', 'thought', 'though', 'tough', 'thorough', 'knight', 'night', 'psychology', 'phonetic', 'algorithm', 'respiration', 'neurology', 'neuron', 'synapse']
const rows = [...new Set([...words, ...extras])].filter(word => word.length > 1 && dictionary.has(word)).map((word, index) => [word, dictionary.get(word), Math.max(1, 100 - index / 100)])
writeFileSync('src/data/pronunciations.ts', `// Generated by scripts/build-lexicon.mjs. See licenses/ and README for sources.\nexport const PRONUNCIATIONS: [string, string, number][] = ${JSON.stringify(rows)}\n`)
console.log(`Generated ${rows.length} pronunciation entries`)
